skylander_t *get_skylander_data(uint16_t id, uint16_t variant) {
  for (int i = 0; i < 702; i++) {
    if (((skylander_db + i)->id == id) &&
        ((skylander_db + i)->variant == variant))
      return (skylander_db + i);
  }
  return (skylander_db + 702);
}

FRESULT read_skylander_bin(FIL *fil, SkylanderDump *dump) {
  UINT bytesRead;
  FRESULT res = f_read(fil, dump->raw_data, SKYLANDER_FILE_SIZE, &bytesRead);

  if (res != FR_OK || bytesRead != SKYLANDER_FILE_SIZE) {
    return (res == FR_OK) ? FR_INT_ERR : res;
  }

  dump->uid = (uint32_t)dump->raw_data[0] | ((uint32_t)dump->raw_data[1] << 8) |
              ((uint32_t)dump->raw_data[2] << 16) |
              ((uint32_t)dump->raw_data[3] << 24);

  uint8_t *block1 = &dump->raw_data[16];
  dump->character_id = (uint16_t)block1[0] | ((uint16_t)block1[1] << 8);

  dump->variant_id = (uint16_t)block1[12] | ((uint16_t)block1[13] << 8);

  return FR_OK;
}